"""009 create alert_events table

Revision ID: 009_alert_events
Revises: 008_audit_events
Create Date: 2026-04-26

WHY SEPARATE FROM AUDIT_EVENTS:
  audit_events is the general ledger — everything goes in there.
  alert_events is specifically for triggered safety/quality alerts
  with structured, queryable columns.

  The difference: you can query alert_events with
  "SELECT * WHERE severity = 'critical' AND compound = 'ibogaine'"
  without parsing JSONB. That query would be possible but ugly and
  slow against audit_events.

WHY ALGORITHM GOVERNANCE COLUMNS:
  FDA "Hurdle 5" — if your software generates a safety alert, you
  must be able to prove:
    1. WHAT algorithm generated it (algorithm_name)
    2. WHICH VERSION of that algorithm (algorithm_version)
    3. WHAT PARAMETERS it was using at the time (algorithm_parameters)

  Without these, a safety alert is unverifiable — the FDA can't
  confirm the alert was generated by a validated algorithm with
  known parameters. These columns make every alert self-documenting.

WHY ACKNOWLEDGED_BY AND ACKNOWLEDGED_AT:
  Clinical protocol requires that safety alerts are acknowledged
  by a human coordinator. An unacknowledged critical alert is a
  protocol violation. These columns track who acknowledged and when,
  creating a complete chain from "system detected anomaly" →
  "human reviewed and acted."
"""

